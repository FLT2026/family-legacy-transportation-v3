const assert=require('node:assert/strict');
const {createApi}=require('./v38-customer-master.js');
const data=new Map([['flt-v32-customers',JSON.stringify([{name:'Legacy Shipper',street:'1 Legacy St',city:'Raleigh',state:'NC',zip:'27601'}])]]);
const storage={getItem:key=>data.get(key)??null,setItem:(key,value)=>data.set(key,String(value))};
let api=createApi(storage);
api.migrate();
assert.equal(api.search('leg')[0].billingAddress.street,'1 Legacy St');
const input={name:'Permanent Customer',type:'Shipper',billingAddress:{street:'10 Billing St',city:'Raleigh',state:'NC',zip:'27601'},phone:'919-555-1234',email:'billing@example.test',primaryContact:'Taylor',contacts:[{name:'Sam',phone:'919-555-2345'}],terms:'Net 30',notes:'Dock appointment'};
const created=api.save(input);assert.ok(created.ok);
const customerId=created.record.id;
api.addLocation(customerId,'pickup',{facility:'Plant A',street:'20 Plant Rd',city:'Raleigh',state:'NC',zip:'27601'});
api.addLocation(customerId,'pickup',{facility:'Plant B',street:'30 Plant Rd',city:'Durham',state:'NC',zip:'27701'});
api.addLocation(customerId,'delivery',{facility:'Depot',street:'40 Depot Rd',city:'Clinton',state:'NC',zip:'28328'});
api=createApi(storage);
assert.equal(api.search('perma')[0].id,customerId);
assert.equal(api.get(customerId).pickupLocations.length,2);
assert.equal(api.get(customerId).deliveryLocations.length,1);
assert.equal(api.get(customerId).contacts[0].name,'Sam');
const load={customerId,customerSnapshot:api.snapshot(customerId),billingAddress:api.snapshot(customerId).billingAddress,invoice:{billToSnapshot:{address:api.snapshot(customerId).billingAddress}},deliveryProof:{signature:'historical'}};
const before=JSON.stringify(load);
api.save({...api.get(customerId),billingAddress:{street:'99 New St',city:'Durham',state:'NC',zip:'27701'}},{reason:'Billing address changed'});
assert.equal(JSON.stringify(load),before,'Customer edits must not mutate historical load/invoice/POD snapshots.');
assert.equal(api.snapshot(customerId).billingAddress.street,'99 New St');
assert.ok(api.get(customerId).history.some(event=>event.before?.billingAddress.street==='10 Billing St'));
assert.equal(api.save({...input,name:'Permanent Customer LLC'}).ok,false,'Matching phone/email must warn before creating a duplicate.');
assert.equal(api.save({...input,name:'permanent CUSTOMER'}).error,'Possible existing customer found.');
assert.ok(api.save({...input,name:'Permanent Customer LLC'},{allowDuplicate:true}).ok,'Explicit duplicate override must not merge records.');
assert.equal(api.list().length,3);
assert.ok(api.archive(customerId,'Company closed').ok);
assert.equal(api.search('Permanent Customer').some(record=>record.id===customerId),false);
assert.equal(JSON.stringify(load),before);
api.migrateLoads([{id:'FLT-OLD',customer:'Historical Customer',billingAddress:{street:'5 Historical Rd',city:'Raleigh',state:'NC',zip:'27601'}},{id:'FLT-ARCHIVED',customer:'Permanent Customer'}]);
assert.equal(api.search('Historical Customer')[0].billingAddress.street,'5 Historical Rd');
assert.equal(api.get(customerId).status,'archived','History migration must not resurrect deliberately deleted customers.');
const invalid='{"unrecognized":"customer data"}',invalidData=new Map([['flt-v32-customers',invalid]]);
const invalidApi=createApi({getItem:key=>invalidData.get(key)??null,setItem:(key,value)=>invalidData.set(key,value)});
assert.equal(invalidApi.save({name:'Must not overwrite damaged data'}).ok,false);
invalidApi.migrateLoads([{id:'FLT-OLD',customer:'Historical Customer'}]);
assert.equal(invalidData.get('flt-v32-customers'),invalid,'Invalid stored customer data must not be silently replaced.');
console.log('Customer master migration, durable search, contacts, multiple locations, duplicate protection, audited edits, and historical snapshot isolation passed.');